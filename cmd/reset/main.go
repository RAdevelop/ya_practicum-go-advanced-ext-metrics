package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"log"
	"os"
	"path/filepath"
	"strings"
)

const (
	markerComment = "generate:reset"
	generatedFile = "reset.gen.go"
	generatedPkg  = "// Code generated by reset generator; DO NOT EDIT.\n\n"
)

func main() {
	root := "."
	if len(os.Args) > 1 {
		root = os.Args[1]
	}

	if err := run(root); err != nil {
		log.Fatalf("reset generator: %v", err)
	}
}

func run(root string) error {
	return filepath.Walk(root, func(path string, info os.FileInfo, err error) error {
		if err != nil {
			return err
		}
		if !info.IsDir() {
			return nil
		}

		// корень — всегда обрабатываем
		if path == root {
			return processPackage(path)
		}

		base := filepath.Base(path)
		// пропускаем служебные и скрытые директории
		if base == "vendor" || base == ".git" ||
			(base != "." && base != ".." && strings.HasPrefix(base, ".")) {
			return filepath.SkipDir
		}
		return processPackage(path)
	})
}

func processPackage(dir string) error {
	fset := token.NewFileSet()

	// парсим все .go файлы пакета, кроме сгенерированного
	var files []*ast.File
	entries, err := os.ReadDir(dir)
	if err != nil {
		return err
	}

	pkgName := ""
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".go") || e.Name() == generatedFile {
			continue
		}
		var f *ast.File
		f, err = parser.ParseFile(fset, filepath.Join(dir, e.Name()), nil, parser.ParseComments)
		if err != nil {
			return fmt.Errorf("parse %s: %w", e.Name(), err)
		}
		if pkgName == "" {
			pkgName = f.Name.Name
		}
		files = append(files, f)
	}

	if len(files) == 0 {
		return nil
	}

	// ищем структуры с // generate:reset
	var structs []*ast.StructType
	var structNames []string

	for _, f := range files {
		for _, decl := range f.Decls {
			gen, ok := decl.(*ast.GenDecl)
			if !ok || gen.Tok != token.TYPE {
				continue
			}
			for _, spec := range gen.Specs {
				ts, ok := spec.(*ast.TypeSpec)
				if !ok {
					continue
				}
				st, ok := ts.Type.(*ast.StructType)
				if !ok {
					continue
				}
				if hasResetMarker(gen, ts) {
					structs = append(structs, st)
					structNames = append(structNames, ts.Name.Name)
				}
			}
		}
	}

	if len(structs) == 0 {
		return nil
	}

	// генерируем код
	buf := &bytes.Buffer{}
	buf.WriteString(generatedPkg)
	buf.WriteString("package ")
	buf.WriteString(pkgName)
	buf.WriteString("\n\n")

	for i, st := range structs {
		writeReset(buf, structNames[i], st)
	}

	// форматируем
	src, err := format.Source(buf.Bytes())
	if err != nil {
		return fmt.Errorf("format: %w\n%s", err, buf.String())
	}

	return os.WriteFile(filepath.Join(dir, generatedFile), src, 0o644)
}

// hasResetMarker проверяет, есть ли // generate:reset в комментарии над типом.
// Маркер может быть на GenDecl (перед type) или на TypeSpec (перед именем).
func hasResetMarker(gen *ast.GenDecl, ts *ast.TypeSpec) bool {
	if gen.Doc != nil {
		for _, c := range gen.Doc.List {
			if strings.TrimSpace(strings.TrimPrefix(c.Text, "//")) == markerComment {
				return true
			}
		}
	}
	if ts.Doc != nil {
		for _, c := range ts.Doc.List {
			if strings.TrimSpace(strings.TrimPrefix(c.Text, "//")) == markerComment {
				return true
			}
		}
	}
	return false
}

func writeReset(buf *bytes.Buffer, name string, st *ast.StructType) {
	recv := strings.ToLower(name[:1])
	_, _ = fmt.Fprintf(buf, "func (%s *%s) Reset() {\n", recv, name)
	_, _ = fmt.Fprintf(buf, "if %s == nil {\nreturn\n}\n", recv)

	for _, field := range st.Fields.List {
		if len(field.Names) == 0 {
			// анонимное поле (встроенное) — пропускаем или обрабатываем отдельно
			continue
		}
		for _, fieldName := range field.Names {
			writeFieldReset(buf, recv, fieldName.Name, field.Type)
		}
	}

	buf.WriteString("}\n\n")
}

func writeFieldReset(buf *bytes.Buffer, recv, fieldName string, typ ast.Expr) {
	access := recv + "." + fieldName

	switch t := typ.(type) {
	case *ast.Ident:
		switch t.Name {
		case "int", "int8", "int16", "int32", "int64",
			"uint", "uint8", "uint16", "uint32", "uint64", "uintptr",
			"float32", "float64", "complex64", "complex128",
			"byte", "rune":
			_, _ = fmt.Fprintf(buf, "%s = 0\n", access)
		case "string":
			_, _ = fmt.Fprintf(buf, "%s = \"\"\n", access)
		case "bool":
			_, _ = fmt.Fprintf(buf, "%s = false\n", access)
		default:
			// возможно, это именованный тип с методом Reset
			_, _ = fmt.Fprintf(buf, "if resetter, ok := any(&%s).(interface{ Reset() }); ok {\nresetter.Reset()\n}\n", access)
		}

	case *ast.StarExpr:
		// указатель
		if isPrimitive(t.X) {
			// *int, *string, *bool
			_, _ = fmt.Fprintf(buf, "if %s != nil {\n*%s = %s\n}\n", access, access, derefZero(t.X))
		} else {
			// *struct, *named type — вызываем Reset у значения
			_, _ = fmt.Fprintf(buf, "if %s != nil {\nif resetter, ok := any(%s).(interface{ Reset() }); ok {\nresetter.Reset()\n}\n}\n", access, access)
		}

	case *ast.ArrayType:
		// слайс: обрезаем по длине
		_, _ = fmt.Fprintf(buf, "%s = %s[:0]\n", access, access)

	case *ast.MapType:
		// мапа: очищаем
		_, _ = fmt.Fprintf(buf, "clear(%s)\n", access)

	case *ast.StructType:
		// анонимная структура: Reset через адрес
		_, _ = fmt.Fprintf(buf, "if resetter, ok := any(&%s).(interface{ Reset() }); ok {\nresetter.Reset()\n}\n", access)

	case *ast.InterfaceType:
		// интерфейс: Reset у значения, если не nil
		_, _ = fmt.Fprintf(buf, "if resetter, ok := %s.(interface{ Reset() }); ok && %s != nil {\nresetter.Reset()\n}\n", access, access)

	default:
		_, _ = fmt.Fprintf(buf, "// TODO: unknown type %T for field %s\n", typ, fieldName)
	}
}

func isPrimitive(e ast.Expr) bool {
	id, ok := e.(*ast.Ident)
	if !ok {
		return false
	}
	switch id.Name {
	case "int", "int8", "int16", "int32", "int64",
		"uint", "uint8", "uint16", "uint32", "uint64", "uintptr",
		"float32", "float64", "complex64", "complex128",
		"byte", "rune":
		return true
	}
	return false
}

func derefZero(e ast.Expr) string {
	id, ok := e.(*ast.Ident)
	if !ok {
		return "nil"
	}
	switch id.Name {
	case "string":
		return `""`
	case "bool":
		return "false"
	default:
		return "0"
	}
}
