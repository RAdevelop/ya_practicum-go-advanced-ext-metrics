// Package main реализует генератор Reset() для структур с маркером
// // generate:reset.
//
// # Назначение
//
// Генератор сканирует все пакеты проекта и для каждой структуры,
// помеченной комментарием // generate:reset, создаёт метод Reset().
// Метод сбрасывает состояние объекта к начальным значениям.
//
// Генерация помогает реализовать паттерн object pool: после Reset()
// объект можно переиспользовать без повторной аллокации.
//
// # Запуск
//
// Собрать бинарник:
//
//	go build -o ./cmd/reset/reset ./cmd/reset
//
// Запустить на всём проекте:
//
//	go run ./cmd/reset .
//
// Запустить на конкретной директории:
//
//	go run ./cmd/reset ./internal
//
// Или через go:generate — добавить в файл с маркером:
//
//	//go:generate go run ../../cmd/reset ../..
//
// и запустить:
//
//	go generate ./...
//
// # Маркер
//
// Структура помечается комментарием // generate:reset непосредственно
// перед объявлением type. Маркер может стоять на строке с type
// (GenDecl.Doc) или перед именем структуры в группе type (TypeSpec.Doc).
//
// Пример:
//
//	// generate:reset
//	type Metrics struct {
//		ID    string
//		Value *float64
//		Tags  []string
//		Stat  map[string]int
//	}
//
// # Правила сброса
//
//   - примитивы (int, uint, float, complex, byte, rune) → 0;
//   - string → "";
//   - bool → false;
//   - слайсы → slice[:0] (длина 0, capacity сохраняется);
//   - мапы → clear(map);
//   - указатели на примитивы → *ptr = zero (если ptr != nil);
//   - указатели на структуры → Reset() у значения (если ptr != nil);
//   - вложенные структуры → Reset() через type assertion;
//   - интерфейсы → Reset() у значения (если не nil);
//   - именованные типы → Reset() через type assertion.
//
// В начале метода проверяется получатель на nil:
//
//	func (m *Metrics) Reset() {
//		if m == nil {
//			return
//		}
//		// ... сброс полей
//	}
//
// # Результат
//
// Для каждого пакета, где найдены маркеры, создаётся файл reset.gen.go
// рядом с исходниками. Файл содержит package-директиву, сгенерированные
// методы и заголовок:
//
//	// Code generated by reset generator; DO NOT EDIT.
//
// Файл перезаписывается при каждом запуске генератора. Не редактируйте
// его вручную — изменения будут потеряны.
//
// Существующие reset.gen.go пропускаются при сканировании — повторный
// запуск не парсит сгенерированный код.
//
// # Сканирование
//
// Обход начинается с корневой директории (аргумент командной строки
// или "." по умолчанию). Пропускаются:
//
//   - vendor;
//   - .git;
//   - все скрытые директории (начинаются с ".").
//
// Корневая директория обрабатывается всегда, даже если её имя начинается
// с ".".
//
// # Ограничения
//
//   - встроенные (анонимные) поля пропускаются;
//   - указатели на слайсы и мапы обрабатываются как обычные указатели —
//     разыменование и сброс значения, а не s[:0] / clear;
//   - циклические ссылки между структурами могут привести к бесконечной
//     рекурсии при вызове Reset() во время выполнения;
//   - поля неизвестных типов (например, func, chan) не сбрасываются —
//     в сгенерированный код добавляется комментарий TODO.
