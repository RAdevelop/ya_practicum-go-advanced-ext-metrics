// Package main реализует multichecker — единый статический анализатор
// для проекта «Сервис сбора метрик и алертинга».
//
// # Запуск
//
// Собрать бинарник:
//
//	go build -o ./cmd/staticlint/staticlint ./cmd/staticlint
//
// Запустить на всём проекте:
//
//	./cmd/staticlint/staticlint ./...
//
// Запустить на конкретных пакетах:
//
//	./cmd/staticlint/staticlint ./cmd/server/... ./cmd/agent/...
//
// Каждый анализатор можно запустить отдельно по имени:
//
//	./cmd/staticlint/staticlint -noexitmain ./...
//	./cmd/staticlint/staticlint -SA1000 ./...
//	./cmd/staticlint/staticlint -printf ./...
//
// Посмотреть список доступных анализаторов:
//
//	./cmd/staticlint/staticlint help
//
// Посмотреть описание конкретного анализатора:
//
//	./cmd/staticlint/staticlint help noexitmain
//
// Подробнее об интерфейсе multichecker:
//
//	https://pkg.go.dev/golang.org/x/tools/go/analysis/multichecker
//
// # Состав анализаторов
//
// 1. Стандартные анализаторы golang.org/x/tools/go/analysis/passes — базовые
// проверки корректности Go-кода, входящие в go vet.
//
// 2. Все анализаторы класса SA (Staticcheck) из honnef.co/go/tools/staticcheck —
// ловят баги, потенциальные ошибки, устаревшие конструкции.
//
// 3. Один анализатор класса ST (Stylecheck) из honnef.co/go/tools/stylecheck —
// стилистические замечания, не влияющие на корректность, но улучшающие
// читаемость и поддерживаемость.
//
// 4. Публичные анализаторы:
//   - nilerr — ловит потерю ошибки при `if err != nil { return nil }`;
//   - bodyclose — ловит незакрытые http.Response.Body.
//
// 5. Собственный анализатор noexitmain — запрещает прямой вызов os.Exit
// в функции main пакета main.
//
// # Стандартные анализаторы x/tools
//
//   - asmdecl — сверяет объявления в Go и ассемблерных файлах.
//   - assign — находит бесполезные присваивания.
//   - atomic — ловит типичные ошибки при работе с sync/atomic.
//   - bools — находит подозрительные булевы операции.
//   - buildtag — проверяет корректность build tags.
//   - composite — находит неименованные поля в составных литералах
//     внешних пакетов (ломкие при изменении структуры).
//   - copylock — находит передачу sync.Mutex и sync.RWMutex по значению.
//   - errorsas — проверяет, что второй аргумент errors.As — указатель
//     на тип, реализующий error.
//   - httpresponse — ловит ошибки при работе с http.Response
//     (незакрытое тело, повторное использование).
//   - ifaceassert — находит невозможные type assertion между интерфейсами.
//   - loopclosure — находит захват переменной цикла во вложенной функции
//     (актуально для Go < 1.22, но полезно и сейчас для явности).
//   - lostcancel — находит невызванный context.CancelFunc.
//   - nilfunc — находит бесполезные сравнения функций с nil.
//   - printf — проверяет соответствие format-строки и аргументов
//     в Printf-подобных функциях.
//   - shadow — находит затенение переменных.
//   - shift — находит сдвиги, превышающие разрядность целого.
//   - stdmethods — проверяет сигнатуры методов, похожих на стандартные
//     интерфейсы (String, Error, Read и т.д.).
//   - stringintconv — находит преобразования int → string
//     (часто ошибочные, дают символ по коду, а не число).
//   - structtag — проверяет корректность тегов структур.
//   - tests — находит типичные ошибки в тестах и примерах.
//   - unmarshal — проверяет, что в json.Unmarshal и подобные
//     передаётся указатель или интерфейс.
//   - unreachable — находит недостижимый код.
//   - unsafeptr — находит некорректные преобразования uintptr
//     в unsafe.Pointer.
//   - unusedresult — находит неиспользованные результаты вызовов
//     «чистых» функций (fmt.Sprintf, errors.New и т.д.).
//
// # Staticcheck SA
//
// Класс SA — Staticcheck Analysis. Содержит более 100 анализаторов,
// которые ловят реальные баги и потенциальные проблемы:
//
//   - SA1xxx — ошибки в стандартной библиотеке (SA1000 — некорректный regexp,
//     SA1019 — использование deprecated API, и т.д.).
//   - SA2xxx — проблемы с конкурентностью (SA2000 — sync.WaitGroup.Add
//     внутри горутины, SA2002 — t.Fatal в горутине теста, и т.д.).
//   - SA3xxx — ошибки в стандартной библиотеке, связанные с типами
//     (SA3000 — TestMain без os.Exit, и т.д.).
//   - SA4xxx — проблемы с типами (SA4000 — сравнение одинаковых выражений,
//     SA4006 — неиспользуемое значение, и т.д.).
//   - SA5xxx — проблемы с производительностью и корректностью
//     (SA5000 — присваивание в nil map, и т.д.).
//   - SA6xxx — проблемы с конкурентностью и каналами (SA6000 — regexp.Match
//     в цикле, SA6005 — неэффективное сравнение строк, и т.д.).
//   - SA9xxx — потенциально опасные конструкции (SA9000 — игнорирование
//     ошибки, SA9003 — пустой блок, и т.д.).
//
// Полный список: https://staticcheck.dev/docs/checks/#SA
//
// # Staticcheck ST
//
// Класс ST — Stylecheck. Стилистические замечания:
//
//   - ST1000 — отсутствует package comment.
//   - ST1001 — dot-import (import . "pkg").
//   - ST1003 — некорректное именование (CamelCase, аббревиатуры).
//   - ST1005 — сообщение об ошибке с большой буквы или с точкой.
//   - ST1012 — имя переменной с ошибкой не начинается с Err.
//   - ST1016 — несогласованные имена ресиверов в методах типа.
//   - ST1020 — комментарий к экспортируемой функции не начинается
//     с имени функции.
//
// В multichecker включён только один анализатор из ST — достаточно
// для требования «не менее одного из остальных классов staticcheck».
//
// Полный список: https://staticcheck.dev/docs/checks/#ST
//
// # Публичные анализаторы
//
//   - nilerr (github.com/gostaticanalysis/nilerr) — находит конструкции
//     вида `if err != nil { return nil }`, когда ошибка теряется.
//     Классический баг: проверка есть, но возвращается nil вместо err.
//
//   - bodyclose (github.com/timakin/bodyclose) — находит http.Response,
//     у которых не закрыт Body. Утечка соединений — частая проблема
//     HTTP-клиентов.
//
// # Собственный анализатор noexitmain
//
// Запрещает прямой вызов os.Exit в функции main пакета main.
//
// Механизм работы:
//
//  1. Проверяется, что пакет имеет имя main (pass.Pkg.Name() == "main").
//  2. Пропускаются тестовые бинарники (суффикс ".test") — это
//     сгенерированный go test код, не наш.
//  3. Пропускаются чужие модули (проверка префикса пути пакета) —
//     анализатор работает только на пакетах нашего проекта.
//  4. В каждом файле ищется импорт "os" (с учётом алиасов и dot-импорта).
//  5. Среди объявлений ищется функция main без ресивера.
//  6. В теле main.main обходятся все узлы AST, ищутся вызовы os.Exit
//     (с учётом алиаса пакета os).
//  7. При нахождении — pass.Reportf с позицией вызова.
//
// Почему запрещено:
//
// os.Exit не выполняет defer-функции. В main это особенно опасно:
// не закроются файлы аудита, не остановятся воркеры, не сохранится
// финальный снапшот метрик.
//
// Ограничения:
//
//   - анализатор ищет только прямой вызов os.Exit в тексте main.main;
//   - вызов через обёртку (log.Fatal, кастомный exit()) не ловится —
//     это осознанный обход, но он требует явного решения разработчика;
//   - рекурсивные вызовы (main вызывает helper, который вызывает os.Exit)
//     не отслеживаются — анализатор работает на уровне AST, не call graph.
